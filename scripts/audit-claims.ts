/**
 * PRIVATE PUBLICATION CHECKLIST
 * Lists every claim, asset and commercial input that must be verified before
 * the site is switched to NEXT_PUBLIC_RELEASE_STAGE=public, and writes it to
 * docs/PUBLICATION-CHECKLIST.md (internal — never linked from the website).
 * Run: npm run audit:claims
 */
import fs from "node:fs";
import { modules } from "../config/features.ts";
import { integrations } from "../config/integrations.ts";
import { securityPrinciples, trustTopics } from "../content/security.ts";
import { articles } from "../content/resources.ts";
import { apps, visibility, independentUse, clearLines } from "../content/collaboration.ts";
import { stages } from "../content/lifecycle.ts";
import { industries } from "../config/industries.ts";
import { policies } from "../config/legal.ts";
import { paletteVerified } from "../config/brand.ts";
import { comparisonApproved, marketModels } from "../config/pricing.ts";
import { regions } from "../config/regions.ts";
import { media } from "../content/media.ts";

let open = 0;
const md: string[] = [
  "# Private Publication Checklist",
  "",
  "_Internal. Generated by `npm run audit:claims` — do not edit by hand, and never link from the website._",
  "",
  "The staging site presents every item below as part of the product. Before setting",
  "`NEXT_PUBLIC_RELEASE_STAGE=public`, verify each one and mark it `verified: true` (or approve/publish it)",
  "in the file named. In the public release, anything still unverified is omitted automatically.",
];
const section = (t: string) => {
  console.log(`\n\u001b[1m${t}\u001b[0m`);
  md.push("", `## ${t}`, "");
};
const item = (t: string) => {
  open++;
  console.log(`  • ${t}`);
  md.push(`- [ ] ${t}`);
};

section("Feature availability register (config/features.ts)");
for (const m of modules)
  for (const c of m.capabilities)
    if (!c.verified) item(`${m.name} → ${c.name} (internal status: ${c.status})`);

section("Integrations (config/integrations.ts)");
for (const i of integrations) if (i.public && !i.verified) item(`${i.name} [${i.status}] — status not verified`);

section("Security statements (content/security.ts)");
for (const s of [...securityPrinciples, ...trustTopics]) if (!s.verified) item(`${s.title} — confirm the control is in place, with engineering evidence`);

section("Legal policies (config/legal.ts)");
for (const p of policies) if (p.status !== "published") item(`${p.title} — unpublished (approved content required)`);

section("Brand, pricing, regions, media");
if (!paletteVerified) item("Brand palette is provisional (config/brand.ts)");
if (!comparisonApproved) item("Plan comparison entitlements not approved (config/pricing.ts)");
for (const [r, m] of Object.entries(marketModels)) if (m?.status !== "approved") item(`Commercial model for ${r} is ${m?.status}`);
for (const r of regions) {
  if (!r.contractingEntity?.verified) item(`${r.name}: contracting entity not confirmed`);
  if (r.complianceStatus !== "verified") item(`${r.name}: compliance status ${r.complianceStatus}`);
}
for (const [k, v] of Object.entries(media)) if (!v.src) item(`Photography slot "${k}" has no licensed image`);

section("Shared projects and collaboration (content/collaboration.ts)");
for (const a of apps) if (!a.verified) item(`App: ${a.name} — confirm what it contributes, reviews, sees and keeps private`);
for (const v of visibility) if (!v.verified) item(`Visibility rule: "${v.item}" — confirm`);
for (const x of [...independentUse, ...clearLines]) if (!x.verified) item(`${x.title} — confirm`);

section("Lifecycle (content/lifecycle.ts)");
for (const st of stages) if (!st.verified) item(`Stage ${st.n}: ${st.title} — confirm role and records`);

section("Industry pages (config/industries.ts)");
for (const ind of industries) for (const j of ind.jobs ?? []) if (!j.verified) item(`${ind.name} → ${j.title}`);

section("Commercial assumptions from the reference file (docs/REFERENCE-REVIEW.md §6)");
for (const t of [
  "Choose the charge basis: workers-or-minimum vs base subscription with included projects/workers plus additions",
  "Confirm billing arrangements per market (flexible +15%, annual −10% on full charge vs on base only)",
  "Confirm markets with price books (Guyana, United States, Canada)",
  "Approve billing rules: office users included, GC not billed for subcontractor workers, invitations don't use project allowance, one subscription per company",
  "Approve plan entitlements (reference capability matrix rows are all 'Not validated')",
  "Approve the 'How subscriptions are sized' explainer on /pricing (partner crews belong to their employer; one company, one account)",
  "Approve plan-suggestion thresholds in the calculator (projects 0–3 / 4–10 / 11+; workers 1–75 / 76–400 / 401+)",
  "Confirm partner programme pathways, markets and process on /partners",
  "Provide an SVG master of the Axtara logo (PNG currently used)",
]) item(t);

section("Resources articles (content/resources.ts)");
for (const a of articles) if (a.status !== "published") item(`"${a.title}" — review and publish`);

section("Configuration");
for (const [k, label] of [
  ["FORMS_WEBHOOK_URL", "Form delivery (or RESEND_API_KEY + FORMS_EMAIL_TO + FORMS_EMAIL_FROM)"],
  ["NEXT_PUBLIC_APP_LOGIN_URL", "Customer login URL"],
  ["NEXT_PUBLIC_SALES_EMAIL", "Public sales email"],
] as const) if (!process.env[k]) item(`${label} — set ${k}`);

md.push("", `**${open} item(s) outstanding.**`, "");
fs.writeFileSync(new URL("../docs/PUBLICATION-CHECKLIST.md", import.meta.url), md.join("\n"));
console.log(`\n${open} item(s) awaiting verification or approval → docs/PUBLICATION-CHECKLIST.md\n`);
